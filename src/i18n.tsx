const dict: Record<Lang, Record<string, string>> = { en, sw, ki }

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: string) => string }

const LangContext = createContext<Ctx>({ lang: 'en', setLang: () => {}, t: (k) => dict.en[k] ?? k })

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem('ack-lang')
      if (saved === 'sw' || saved === 'ki' || saved === 'en') return saved
    } catch { /* ignore */ }
    return 'en'
  })

  const setLang = (l: Lang) => {
    setLangState(l)
    try { localStorage.setItem('ack-lang', l) } catch { /* ignore */ }
  }

  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  const t = (k: string) => dict[lang][k] ?? dict.en[k] ?? k

  return <LangContext.Provider value={{ lang, setLang, t }}>{children}</LangContext.Provider>
}

export function useI18n() {
  return useContext(LangContext)
}
